#!/usr/bin/env python3
"""Validate and report the HBC C-to-Rust parity ledger."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "config" / "parity-ledger.csv"
REPORT = ROOT / "docs" / "generated" / "parity-status.md"
C_SOURCE = ROOT / ".." / ".." / "C-sources" / "hbc" / "channel" / "channelapp"
FIELDS = (
    "id",
    "area",
    "c_ref",
    "rust_ref",
    "coverage",
    "review",
    "verification",
    "evidence",
    "next_step",
)
COVERAGE = {"implemented", "partial", "open", "out_of_scope"}
REVIEW = {"not_reviewed", "source_reviewed", "needs_followup", "excluded"}
VERIFICATION = {"not_run", "host_tested", "target_checked", "hardware_pending", "not_applicable"}


def load_rows() -> list[dict[str, str]]:
    with LEDGER.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if tuple(reader.fieldnames or ()) != FIELDS:
            raise ValueError(f"{LEDGER}: expected columns {','.join(FIELDS)}")
        rows = list(reader)
    seen: set[str] = set()
    for line, row in enumerate(rows, 2):
        for field in FIELDS:
            if row[field] is None:
                raise ValueError(f"{LEDGER}:{line}: missing {field}")
        if not row["id"] or row["id"] in seen:
            raise ValueError(f"{LEDGER}:{line}: blank or duplicate id {row['id']!r}")
        seen.add(row["id"])
        if row["coverage"] not in COVERAGE:
            raise ValueError(f"{LEDGER}:{line}: invalid coverage {row['coverage']}")
        if row["review"] not in REVIEW:
            raise ValueError(f"{LEDGER}:{line}: invalid review state {row['review']}")
        if row["verification"] not in VERIFICATION:
            raise ValueError(f"{LEDGER}:{line}: invalid verification {row['verification']}")
        if row["coverage"] == "out_of_scope" and row["review"] != "excluded":
            raise ValueError(f"{LEDGER}:{line}: out-of-scope row must have review=excluded")
        validate_ref(row["c_ref"], C_SOURCE, LEDGER, line)
        validate_ref(row["rust_ref"], ROOT, LEDGER, line)
        evidence = row["evidence"]
        if evidence and not (ROOT / evidence.split("#", 1)[0]).is_file():
            raise ValueError(f"{LEDGER}:{line}: missing evidence file {evidence}")
        if row["coverage"] in {"partial", "open"} and not row["next_step"].strip():
            raise ValueError(f"{LEDGER}:{line}: unresolved row needs a next_step")
    if not rows:
        raise ValueError(f"{LEDGER}: no parity rows")
    return rows


def validate_ref(reference: str, base: Path, ledger: Path, line: int) -> None:
    if base == C_SOURCE and reference.startswith("scope:") and len(reference) > 6:
        return
    path_text, separator, symbol = reference.partition("#")
    path = (base / path_text).resolve()
    if not path.is_relative_to(base.resolve()) or not path.is_file():
        raise ValueError(f"{ledger}:{line}: invalid source reference {reference}")
    if not separator or not symbol.strip():
        raise ValueError(f"{ledger}:{line}: reference needs path#symbol: {reference}")
    if symbol not in path.read_text(encoding="utf-8", errors="replace"):
        raise ValueError(f"{ledger}:{line}: symbol {symbol!r} not found in {path}")


def render(rows: list[dict[str, str]]) -> str:
    counts = {state: sum(row["coverage"] == state for row in rows) for state in COVERAGE}
    review_counts = {state: sum(row["review"] == state for row in rows) for state in REVIEW}
    hardware_pending = sum(row["verification"] == "hardware_pending" for row in rows)
    lines = [
        "# HBC C-to-Rust parity status",
        "",
        "Generated by `python3 tools/parity.py refresh`. Do not edit this file.",
        "",
        "Coverage describes the recorded Rust implementation. Review and verification are separate:",
        "a build or host test does not prove source parity or real Wii behavior.",
        "",
        f"Tracked areas: **{len(rows)}** — implemented: **{counts['implemented']}**, "
        f"partial: **{counts['partial']}**, open: **{counts['open']}**, "
        f"out of scope: **{counts['out_of_scope']}**.",
        "",
        f"Source review: **{review_counts['source_reviewed']} reviewed**, "
        f"**{review_counts['not_reviewed']} pending**, "
        f"**{review_counts['needs_followup']} need follow-up**. "
        f"Real Wii verification pending for **{hardware_pending}** areas.",
        "",
        "| ID | Area | C reference | Rust reference | Coverage | Review | Verification | Next step |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        c_ref = f"`{row['c_ref']}`"
        rust_ref = f"`{row['rust_ref']}`"
        cells = (
            row["id"], row["area"], c_ref, rust_ref, row["coverage"],
            row["review"], row["verification"], row["next_step"] or "—",
        )
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
    lines.extend(
        [
            "",
            "## State definitions",
            "",
            "- `implemented`: the port status records the behavior as implemented; source review can still be open.",
            "- `partial`: some behavior is present, with known gaps recorded in the next step.",
            "- `open`: Rust work or source comparison remains.",
            "- `out_of_scope`: the behavior is excluded from the running HBC application parity target.",
            "- `source_reviewed`: a recorded source comparison is complete for this area.",
            "- `hardware_pending`: real Wii behavior has not been verified.",
            "",
            "The source links point to C HBC under `C-sources/hbc/channel/channelapp/source`. "
            "Update the CSV ledger, then run `python3 tools/parity.py refresh` and "
            "`python3 tools/parity.py check`.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("check", "status", "refresh"))
    args = parser.parse_args()
    try:
        rows = load_rows()
        report = render(rows)
        if args.command == "refresh":
            REPORT.parent.mkdir(parents=True, exist_ok=True)
            REPORT.write_text(report, encoding="utf-8")
            print(f"updated {REPORT.relative_to(ROOT)} ({len(rows)} areas)")
        elif args.command == "check":
            if not REPORT.is_file() or REPORT.read_text(encoding="utf-8") != report:
                raise ValueError(f"{REPORT} is stale; run python3 tools/parity.py refresh")
            print(f"parity ledger and report are current ({len(rows)} areas)")
        else:
            print(report, end="")
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
