#!/usr/bin/env python3
"""Generate the in-crate HBC translation table from C HBC PO catalogs."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
CATALOGS = ROOT / ".." / ".." / "C-sources" / "hbc" / "channel" / "channelapp" / "i18n"
OUTPUT = ROOT / "src" / "localization_catalog.rs"
LANGUAGES = {
    "spanish": "Spanish",
    "french": "French",
    "german": "German",
    "dutch": "Dutch",
    "italian": "Italian",
    "japanese": "Japanese",
}


def read_catalog(path: Path) -> dict[str, str]:
    entries: list[dict[str, str]] = []
    current: str | None = None
    entry: dict[str, str] = {}
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("msgid "):
            if current is not None:
                entries.append(entry)
            current = "msgid"
            entry = {current: ast.literal_eval(line[6:])}
        elif line.startswith("msgstr ") and current is not None:
            current = "msgstr"
            entry[current] = ast.literal_eval(line[7:])
        elif line.startswith('"') and current is not None:
            try:
                entry[current] += ast.literal_eval(line)
            except (SyntaxError, ValueError) as error:
                raise ValueError(f"{path}:{line_number}: invalid PO string") from error
    if current is not None:
        entries.append(entry)

    catalog: dict[str, str] = {}
    for item in entries:
        source = item.get("msgid", "")
        translated = item.get("msgstr", "")
        if not source:
            continue
        if not translated:
            raise ValueError(f"{path}: empty translation for {source!r}")
        if source in catalog:
            raise ValueError(f"{path}: duplicate message id {source!r}")
        catalog[source] = translated
    return catalog


def rust_string(value: str) -> str:
    # PO strings in the HBC catalogs do not contain Rust raw-string delimiters.
    import json

    return json.dumps(value, ensure_ascii=False)


def render() -> str:
    catalogs = {
        language: read_catalog(CATALOGS / f"{stem}.po")
        for stem, language in LANGUAGES.items()
    }
    expected = set(next(iter(catalogs.values())))
    if any(set(catalog) != expected for catalog in catalogs.values()):
        raise ValueError("C HBC language catalogs have different message ids")

    lines = [
        "// Generated by `python3 tools/generate-localization.py`; do not edit.",
        "use super::Language;",
        "",
        "pub(super) fn lookup(language: Language, source: &str) -> Option<&'static str> {",
        "    let catalog = match language {",
        "        Language::English => return None,",
    ]
    for stem, language in LANGUAGES.items():
        lines.append(f"        Language::{language} => {stem.upper()},")
    lines.extend(["    };", "    catalog.iter().find_map(|(key, value)| (*key == source).then_some(*value))", "}", ""])
    for stem, language in LANGUAGES.items():
        catalog = catalogs[language]
        lines.append(f"const {stem.upper()}: &[(&str, &str)] = &[")
        for source, translated in catalog.items():
            lines.append(f"    ({rust_string(source)}, {rust_string(translated)}),")
        lines.extend(["];", ""])
    generated = "\n".join(lines)
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=generated,
        text=True,
        capture_output=True,
        check=True,
    )
    return formatted.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = render()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
                raise ValueError(f"{OUTPUT} is stale; run python3 tools/generate-localization.py")
            print("localization catalog matches all six C HBC PO files")
        else:
            OUTPUT.write_text(generated, encoding="utf-8")
            print(f"updated {OUTPUT.relative_to(ROOT)}")
    except (OSError, ValueError) as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
